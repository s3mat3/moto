#include <iostream>
#include <vector>
#include <fstream>
#include <filesystem>

#include "result.hpp"

/** read_config_value
 *
 * Returns an int on success and moto::Error on failure.
 * 静的メソッド moto::Result::fail を使用した例。
 */
moto::Result<int> read_config_value(const std::string& key) {
    if (key == "timeout") {
        return 30; // Success: Implicit conversion from T to Result
    } else if (key == "port") {
        return 8080;
    } else {
        // Concisely generate errors using Result::fail
        return moto::Result<int>::fail(404, "Key not found: " + key);
    }
}

/** create_dummy_file
 *
 * Does not return a value on success, only returns an error on failure.
 * Result<void> と moto::Result::fail_errno を使用した例。
 */
moto::Result<void> create_dummy_file(const std::string& filename) {
    std::ofstream file(filename);
    if (!file) {
        // Automatically obtain errno, generate Error, and return as Result<void>
        // ※Actually, std::ofstream may not update errno directly, but assumes a
        // situation where errno is generated by an operation similar to a system
        // call.
        return moto::Result<void>::fail_errno("Could not create file: " + filename);
    }
    file << "dummy data";
    return {}; // Success: Default constructor for Result<void>
}

int main() {
    // --- Case 1: Value Result ---
    std::cout << "--- Config Reading Test ---" << std::endl;
    std::vector<std::string> keys_to_read = {"timeout", "unknown_key", "port"};

    for (const auto& key : keys_to_read) {
        std::cout << "Reading " << key << "... ";
        auto result = read_config_value(key);

        if (result) {
            std::cout << "Success! Value = " << result.value() << std::endl;
        } else {
            const auto& err = result.error();
            std::cout << "Error! [" << err.code << "] " << err.cause << std::endl;
        }
    }

    // --- Case 2: Void Result and errno ---
    std::cout << "\n--- File Creation Test ---" << std::endl;

    // Simulate errors by specifying a path without write permission, etc.
    std::vector<std::string> files_to_create = {"test.txt", "/invalid_path/test.txt"};

    for (const auto& filename : files_to_create) {
        std::cout << "Creating " << filename << "... ";
        auto result = create_dummy_file(filename);

        if (result) {
            std::cout << "Success!" << std::endl;
        } else {
            const auto& err = result.error();
            std::cout << "Error! [" << err.code << "] " << err.cause << std::endl;
        }
    }

    return 0;
}
